"""Keep SQLite on the computer and use PostgreSQL for the hosted copy."""
import os
import sqlite3

class PostgresConnection:
    postgres=True

    def __init__(self,dsn):
        try:
            import psycopg
        except ImportError:
            raise RuntimeError('Instale requirements.txt para usar o banco online.') from None
        try:
            self.connection=psycopg.connect(dsn,connect_timeout=12,application_name='lojinha',prepare_threshold=None)
        except (psycopg.Error,ValueError):
            raise ConnectionError('Não foi possível conectar ao banco online. Confira a configuração do serviço.') from None

    def execute(self,statement,params=()):
        return self.connection.execute(statement.replace('?','%s'),params)

    def commit(self):self.connection.commit()
    def rollback(self):self.connection.rollback()
    def close(self):self.connection.close()

def open_connection(data_dir):
    dsn=os.environ.get('LOJINHA_DATABASE_URL','').strip()
    if dsn:return PostgresConnection(dsn)
    if os.environ.get('LOJINHA_REQUIRE_POSTGRES')=='1':
        raise RuntimeError('Configure LOJINHA_DATABASE_URL antes de iniciar a versão online.')
    data_dir.mkdir(parents=True,exist_ok=True)
    connection=sqlite3.connect(data_dir/'lojinha.sqlite3',timeout=20)
    connection.execute('PRAGMA journal_mode=WAL')
    return connection

def begin(connection):
    if getattr(connection,'postgres',False):
        connection.execute("SET LOCAL lock_timeout = '15s'")
        connection.execute('SET LOCAL search_path TO lojinha, pg_catalog')
        # Serialize business transactions, preserving the same inventory/payment
        # semantics as BEGIN IMMEDIATE in the local database.
        connection.execute('SELECT pg_advisory_xact_lock(169794482713)')
    else:
        connection.execute('BEGIN IMMEDIATE')

def prepare_schema(connection):
    is_postgres=getattr(connection,'postgres',False)
    if is_postgres:
        connection.execute('CREATE SCHEMA IF NOT EXISTS lojinha')
        connection.execute('REVOKE ALL ON SCHEMA lojinha FROM PUBLIC')
    position=', seq BIGINT GENERATED BY DEFAULT AS IDENTITY' if is_postgres else ''
    connection.execute('CREATE TABLE IF NOT EXISTS records (kind TEXT NOT NULL, id TEXT NOT NULL, doc TEXT NOT NULL'+position+', PRIMARY KEY(kind,id))')
    connection.execute('CREATE TABLE IF NOT EXISTS settings (id INTEGER PRIMARY KEY CHECK(id=1), doc TEXT NOT NULL)')
    connection.execute('CREATE TABLE IF NOT EXISTS restore_history (id TEXT PRIMARY KEY, snapshot TEXT NOT NULL)')
